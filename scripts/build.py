"""Generate README.md and categories/*.md from items.json.

items.json is the only file to edit by hand (or by the weekly sync task).
Run: python3 scripts/build.py   (add --check to fail if files are out of date)
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
A = 'https://claude.ai/artifact/'
G = 'https://github.com/danll737321-beep/'
P = 'https://danll737321-beep.github.io/'
CATS = [('github', 'GitHub', 'github.md')]  # public site shows GitHub only

def key(i):
    return re.sub(r'^[-_]+', '', i['t']).lower()

def md(s):
    return s.replace('|', '\\|')

def zh(i):
    return f"[Chinese]({A}{i['alt']})" if i.get('alt') else ''

def table(k, items):
    if k == 'github':
        rows = ['| Repo | Site | Note |', '|---|---|---|']
        rows += [f"| [{md(i['t'])}]({G}{i['id']}) | [Pages]({P}{i['id']}/) | {md(i['n'])} |" for i in items]
    elif k == 'project':
        rows = ['| Project | Link |', '|---|---|']
        rows += [f"| {md(i['t'])} | [Projects](https://claude.ai/projects) |" for i in items]
    else:
        rows = ['| Title | Chinese |', '|---|---|']
        rows += [f"| [{md(i['t'])}]({A}{i['id']}) | {zh(i)} |" for i in items]
    return '\n'.join(rows)

def build():
    raw = json.loads((ROOT / 'items.json').read_text(encoding='utf-8'))['items']
    data = [i for i in raw if i['k'] == 'github']  # public site: GitHub only
    out = {'items.json': json.dumps({'items': data}, ensure_ascii=False, indent=1) + '\n'}
    readme = ['# Daniel Hub', '',
              "Daniel Hub — all of Daniel's GitHub repos in one place.", '',
              '**Open the app:** https://danll737321-beep.github.io/Daniel-Hub/', '',
              'Sorted A–Z.', '',
              '<!-- Generated by scripts/build.py from items.json. Do not edit by hand. -->', '']
    for n, (k, name, fn) in enumerate(CATS):
        items = sorted((i for i in data if i['k'] == k), key=key)
        if not items:
            continue
        readme += [f"<details{' open' if n == 0 else ''}>", f'<summary><b>{name}</b> ({len(items)})</summary>', '',
                   table(k, items), '', f'[Own page](categories/{fn})', '', '</details>', '']
        out[f'categories/{fn}'] = f'# {name} ({len(items)})\n\n[← Back](../README.md)\n\n{table(k, items)}\n'
    out['README.md'] = '\n'.join(readme)
    return out

if __name__ == '__main__':
    files = build()
    stale = [p for p, c in files.items() if not (ROOT / p).exists() or (ROOT / p).read_text(encoding='utf-8') != c]
    if '--check' in sys.argv:
        if stale:
            sys.exit('Out of date (run python3 scripts/build.py): ' + ', '.join(stale))
        print('README and categories are up to date.')
    else:
        for p, c in files.items():
            (ROOT / p).parent.mkdir(exist_ok=True)
            (ROOT / p).write_text(c, encoding='utf-8')
        print('Wrote', len(files), 'files;', len(stale), 'changed.')
